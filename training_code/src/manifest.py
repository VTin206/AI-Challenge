"""Write data_manifest.json describing every training input and generated artifact."""
from __future__ import annotations

import argparse
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--data", type=Path, default=Path("training_code/data"))
    p.add_argument("--zips", nargs="*", type=Path, default=[])
    p.add_argument("--split-file", type=Path, default=Path("configs/split.json"))
    p.add_argument("--gen-config", type=Path, default=Path("configs/slm.json"))
    p.add_argument("--out", type=Path, default=Path("training_code/data_manifest.json"))
    a = p.parse_args()
    files = sorted(f for f in a.data.rglob("*") if f.is_file())
    sft = a.data / "sft.jsonl"
    manifest = {
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "sources": "competition train split + trajectories generated by an open teacher model; public/private test never used for training",
        "competition_zips": {z.name: sha256(z) for z in a.zips if z.exists()},
        "split": json.loads(a.split_file.read_text(encoding="utf-8")) if a.split_file.exists() else None,
        "teacher": json.loads(a.gen_config.read_text(encoding="utf-8")).get("gen") if a.gen_config.exists() else None,
        "sft_samples": sum(1 for line in sft.open(encoding="utf-8") if line.strip()) if sft.exists() else 0,
        "files": [{"path": str(f.relative_to(a.data)), "bytes": f.stat().st_size, "sha256": sha256(f)} for f in files],
        "nondeterministic_steps": ["vLLM sampling (seeded, batch-dependent)", "GPU training kernels"],
        "public_test_overlap": 0,
    }
    a.out.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"wrote {a.out} ({len(files)} files)")


if __name__ == "__main__":
    main()
